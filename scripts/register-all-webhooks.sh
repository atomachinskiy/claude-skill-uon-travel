# Фильтр по типам если задан --types
declare -a ACTIVE_TYPES
if [[ -n "$TYPES_FILTER" ]]; then
    IFS=',' read -ra ACTIVE_TYPES <<< "$TYPES_FILTER"
else
    ACTIVE_TYPES=("${!EVENTS[@]}")
fi

echo "📡 Регистрирую $((${#ACTIVE_TYPES[@]})) вебхуков на URL: $URL (метод $METHOD)"
echo ""

REGISTERED=0
FAILED=0
for tid in "${ACTIVE_TYPES[@]}"; do
    desc="${EVENTS[$tid]:-unknown}"
    note="$NOTE_PREFIX | $desc"
    resp=$(uon_post "webhook/create" "type_id=$tid" "url=$URL" "method=$METHOD" "note=$note")
    wid=$(echo "$resp" | python3 -c "import sys,json;d=json.load(sys.stdin);print(d.get('id',''))" 2>/dev/null || echo '')
    result=$(echo "$resp" | python3 -c "import sys,json;d=json.load(sys.stdin);print(d.get('result',''))" 2>/dev/null || echo '')
    if [[ "$result" == "200" && -n "$wid" ]]; then
        echo "  ✅ $tid → $desc (webhook_id=$wid)"
        REGISTERED=$((REGISTERED+1))
    else
        echo "  ❌ $tid → $desc: $resp"
        FAILED=$((FAILED+1))
    fi
done

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━"
