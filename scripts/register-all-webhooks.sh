#!/usr/bin/env bash
# register-all-webhooks.sh — массовая регистрация всех 69 типов webhook-событий U-On на один URL.
#
# Использование:
#   ./scripts/register-all-webhooks.sh https://my-receiver.example.com/uon-webhook
#   ./scripts/register-all-webhooks.sh https://my-receiver.example.com --method POST
#   ./scripts/register-all-webhooks.sh https://my-receiver.example.com --types 2,16,17,9   # только заявки и платежи
#
# Перед запуском подложите URL receiver-а (cloudflare-worker, fastapi, n8n, telegram-bridge).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_common.sh
source "$SCRIPT_DIR/_common.sh"

URL=""
METHOD="POST"
NOTE_PREFIX="auto by claude-skill-uon-travel"
TYPES_FILTER=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --method) METHOD="$2"; shift 2 ;;
        --types) TYPES_FILTER="$2"; shift 2 ;;
        --note-prefix) NOTE_PREFIX="$2"; shift 2 ;;
        -h|--help)
            grep -E '^# ' "$0" | sed 's/^# //'
            exit 0
            ;;
        *)
            if [[ -z "$URL" ]]; then
                URL="$1"
            else
                echo "Unknown arg: $1" >&2
                exit 1
            fi
            shift
            ;;
    esac
done

if [[ -z "$URL" ]]; then
    echo "❌ URL не задан. Пример: $0 https://receiver.example.com/wh" >&2
    exit 1
fi

